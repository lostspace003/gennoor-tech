"""Builds src/data/partnerships/<key>.ts from the toolkits in New-Partnerships (workbook + email console).
Run: python -I scripts/build-partnership-seeds.py
The CRM copies a seed into its own store the first time a segment opens; after that the store is the truth."""
import re, json, glob, os, openpyxl
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'New-Partnerships')
OUT = os.path.join(ROOT, 'src', 'data', 'partnerships')
os.makedirs(OUT, exist_ok=True)
SEGMENTS = {  # key: (folder, kind)   kind 'inst' = Institution_Database columns, 'org' = Organization_Database columns
  'india-universities': ('GENNOOR_India_Universities_Toolkit', 'inst'),
  'mumbai-colleges': ('GENNOOR_Mumbai_Colleges_Toolkit', 'inst'),
  'pune-colleges': ('GENNOOR_Pune_Colleges_Toolkit', 'inst'),
  'mid-size-corporates': ('GENNOOR_MidSize_Corporates_Toolkit', 'org'),
  'government-skilling': ('GENNOOR_Govt_Skilling_Initiatives_Toolkit', 'org'),
}
s = lambda v: '' if v is None else str(v).strip()
EMAIL = re.compile(r'[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}')

def sheet(wb, *names):
    for n in names:
        if n in wb.sheetnames: return wb[n]
    raise KeyError(names)

def rows(ws):
    r = list(ws.iter_rows(values_only=True))
    hi = next(i for i, x in enumerate(r) if x and s(x[0]) in ('Lead ID', 'Contact ID'))
    return [x for x in r[hi + 1:] if x and s(x[0])]

def emails_of(text): return list(dict.fromkeys(EMAIL.findall(text or '')))

def real_phone(v):
    v = s(v)
    return len(re.findall(r'\d', v)) >= 6 and not re.search(r'portal|helpdesk|not publicly|not listed|ariba', v, re.I)

def reachable(official, phone, contacts):
    # A lead with no email and no phone anywhere (owner, 28 November 2026) is not kept
    return bool(emails_of(official)) or real_phone(phone) or any(c['email'] or real_phone(c['phone']) for c in contacts)

for key, (folder, kind) in SEGMENTS.items():
    d = os.path.join(SRC, folder)
    wb = openpyxl.load_workbook(glob.glob(os.path.join(d, '*.xlsx'))[0], data_only=True)
    orgs = rows(sheet(wb, 'Institution_Database', 'Organization_Database'))
    dms = rows(wb['Decision_Makers'])
    html = open(glob.glob(os.path.join(d, '*Console.html'))[0], encoding='utf8').read()
    i = html.index('const EMAILS') ; i = html.index('=', i) + 1
    EM, _ = json.JSONDecoder().raw_decode(html[i:].lstrip())
    master = EM[0]
    by_name = {e['institution']: e for e in EM[1:]}
    seed = []
    for r in orgs:
        (lid, name, zone, city, site, typ, dept, dept_url, dm, desig, official, status, phone, evid, offering, hook, prio, src) = [s(x) for x in r[:18]]
        contacts = []
        for c in dms:
            if s(c[1]) != name: continue
            em = s(c[8])
            found = emails_of(em)
            contacts.append(dict(id=s(c[0]), name=s(c[6]), designation=s(c[7]), email=found[0] if found else '', emailNote=em, status=s(c[9]),
                                 linkedin=s(c[10]), phone=s(c[11]), department=s(c[12]), source=s(c[13]), notes='', order=s(c[5])))
        if not reachable(official, phone, contacts): continue
        e = by_name.get(name)
        to = emails_of(e['to']) if e else emails_of(official)
        draft = dict(subject=e['subject'], body=e['body'], to=to[:6], cc=emails_of(e.get('cc_extra', ''))[:6], toLabel=(dm + ' — ' + desig).strip(' —'), pitch=e.get('pitch', '')) if e else None
        seed.append(dict(id=lid, name=name, region=zone, country=city, city=city, website=site, type=typ, department=dept, departmentUrl=dept_url,
                         decisionMaker=dm, designation=desig, officialEmail=official, emailStatus=status, phone=phone, evidence=evid,
                         offering=offering, priority=prio, hook=hook, sourceUrl=src, contacts=contacts, draft=draft))
    ts = ("// Generated by scripts/build-partnership-seeds.py from New-Partnerships/%s. The CRM copies this into its own store the first\n"
          "// time the segment opens; after that the store is the truth and this file is only the seed.\n"
          "import type { SeedUniversity, MasterEmail } from '@/lib/crm/universities-types'\n\n"
          "export const SEED: SeedUniversity[] = %s\n\n"
          "export const MASTER: MasterEmail = %s\n") % (folder, json.dumps(seed, indent=1, ensure_ascii=False), json.dumps(dict(subject=master['subject'], body=master['body']), indent=1, ensure_ascii=False))
    open(os.path.join(OUT, key + '.ts'), 'w', encoding='utf8').write(ts)
    print(key, len(seed), 'orgs', sum(len(x['contacts']) for x in seed), 'contacts', sum(1 for x in seed if x['draft']), 'drafts', sum(1 for x in seed if x['draft'] and not x['draft']['to']), 'without address')
