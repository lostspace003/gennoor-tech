/**
 * Escape a value for safe interpolation into HTML email templates.
 * User-supplied form fields must pass through this before being embedded
 * in any html string handed to the email service.
 */
export function escapeHtml(value: unknown): string {
  if (value === null || value === undefined) return ''
  return String(value)
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;')
}
