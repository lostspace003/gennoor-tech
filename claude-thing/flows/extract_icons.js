/* Pulls the SVG path data of the icons the flow engine uses out of lucide-react (already a dependency)
   and writes claude-thing/flows/engine/icons.js so the engine runs without any network or bundler.
   Run: node claude-thing/flows/extract_icons.js */
const fs = require('fs');
const path = require('path');

const NAMES = [
  'user', 'users', 'sparkles', 'server', 'database', 'file-text', 'file-spreadsheet', 'message-square', 'code',
  'hash', 'shield-check', 'lock', 'key-round', 'wrench', 'settings', 'cloud', 'folder', 'book-open', 'check', 'x',
  'triangle-alert', 'clock', 'coins', 'chart-line', 'globe', 'plug', 'bot', 'brain', 'eye', 'target', 'scale',
  'git-branch', 'layers', 'search', 'mail', 'building-2', 'stethoscope', 'siren', 'gauge', 'workflow', 'repeat',
  'clipboard-list', 'terminal', 'cpu', 'network', 'timer', 'flag', 'rocket', 'link-2', 'badge-check', 'boxes',
  'list-checks', 'lightbulb', 'graduation-cap', 'trophy', 'map', 'route', 'activity', 'scissors', 'calculator',
  'folder-kanban', 'history', 'radar', 'puzzle', 'compass', 'zap', 'send', 'inbox', 'file-code', 'file-check',
  'file-warning', 'ban', 'circle-help', 'refresh-cw', 'arrow-right', 'package', 'briefcase', 'landmark', 'heart-pulse',
  'receipt', 'ticket', 'headset', 'monitor', 'smartphone', 'cloud-cog', 'shield-alert', 'shield', 'fingerprint',
  'eye-off', 'filter', 'split', 'merge', 'play', 'pause', 'square-check', 'circle-x', 'circle-check', 'chart-bar',
  'table', 'image', 'notebook-pen', 'pen-line', 'sliders-horizontal', 'toggle-right', 'bell', 'megaphone', 'bug',
  'test-tube', 'flask-conical', 'microscope', 'ruler', 'crown', 'handshake', 'phone', 'calendar', 'dollar-sign',
  'percent', 'trending-up', 'trending-down', 'alarm-clock', 'hourglass', 'lightbulb-off', 'battery-charging',
];

const dir = path.join(__dirname, '..', '..', 'node_modules', 'lucide-react', 'dist', 'esm', 'icons');
const out = {};
const missing = [];
for (const n of NAMES) {
  const p = path.join(dir, n + '.js');
  if (!fs.existsSync(p)) { missing.push(n); continue; }
  const src = fs.readFileSync(p, 'utf8');
  const m = src.match(/const __iconNode = (\[[\s\S]*?\]);\n/);
  if (!m) { missing.push(n); continue; }
  // the node list is JS, not JSON: quote the bare keys
  const js = m[1];
  // eslint-disable-next-line no-new-func
  const node = new Function('return ' + js)();
  out[n] = node.map(([tag, attrs]) => { const a = { ...attrs }; delete a.key; return [tag, a]; });
}
fs.mkdirSync(path.join(__dirname, 'engine'), { recursive: true });
fs.writeFileSync(path.join(__dirname, 'engine', 'icons.js'), '/* generated by extract_icons.js from lucide-react */\nwindow.FLOW_ICONS = ' + JSON.stringify(out) + ';\n');
console.log('icons:', Object.keys(out).length, missing.length ? 'missing: ' + missing.join(', ') : 'all found');
